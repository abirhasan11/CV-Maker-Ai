/**
 * Safe Theme Getter with fallback
 */
export const getThemeColors = (themeKey: ColorTheme): ThemeColorSet => {
  return THEME_COLORS[themeKey] || THEME_COLORS.navy;
};

export const getFontFamilyClass = (font: FontFamily): string => {
  switch (font) {
    case 'serif':
      return 'font-serif';
    case 'mono':
      return 'font-mono';
    case 'sans':
    default:
      return 'font-sans';
  }
};

export const getFontSizeClasses = (size: FontSize) => {
  switch (size) {
    case 'sm':
      return {
        name: 'text-xl font-bold',
        sectionHeading: 'text-xs font-bold uppercase tracking-wider',
        title: 'text-sm font-semibold',
        body: 'text-xs leading-relaxed',
        subtext: 'text-[11px] text-slate-500',
      };
    case 'lg':
      return {
        name: 'text-3xl font-extrabold',
        sectionHeading: 'text-base font-bold uppercase tracking-wider',
        title: 'text-base font-semibold',
        body: 'text-sm leading-relaxed',
        subtext: 'text-xs text-slate-500',
      };
    case 'md':
    default:
      return {
        name: 'text-2xl font-bold',
        sectionHeading: 'text-sm font-bold uppercase tracking-wider',
        title: 'text-sm font-bold',
        body: 'text-[13px] leading-relaxed',
        subtext: 'text-xs text-slate-500',
      };
  }
};

export const getSpacingClasses = (density: SpacingDensity) => {
  switch (density) {
    case 'compact':
      return {
        sectionGap: 'mb-3',
        itemGap: 'space-y-1.5',
        padding: 'p-6',
        bulletGap: 'space-y-0.5',
      };
    case 'spacious':
      return {
        sectionGap: 'mb-6',
        itemGap: 'space-y-4',
        padding: 'p-10',
        bulletGap: 'space-y-2',
      };
    case 'normal':
    default:
      return {
        sectionGap: 'mb-4',
        itemGap: 'space-y-2.5',
        padding: 'p-8',
        bulletGap: 'space-y-1',
      };
  }
};
